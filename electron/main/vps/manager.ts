/*
 * VPS Manager: one operation at a time (convert, disconnect, new password,
 * recover), each a single administrator prompt running a script generated by
 * the platform adapter. State lives in the manifest (config.ts); the password
 * in credentials.ts; nothing here runs in the background.
 */

const STEP_LABELS: Record<VpsStepId, string> = {
  checks: 'Check this computer',
  port: 'Choose a free port',
  credentials: 'Generate credentials',
  authorize: 'Administrator approval',
  install: 'Install the SSH server',
  user: 'Set up the VPS account',
  config: 'Configure SSH',
  firewall: 'Firewall',
  service: 'Start the server',
  verify: 'Verify the server'
}
/** The same steps, worded for Disconnect / Clean up. */
const TEARDOWN_LABELS: Partial<Record<VpsStepId, string>> = {
  service: 'Stop and remove the server',
  firewall: 'Remove the firewall rule',
  user: 'Remove or disable the VPS account',
  install: 'Remove the SSH server (if the app installed it)',
  config: 'Remove the server files'
}
const SETUP_STEPS: VpsStepId[] = ['checks', 'port', 'credentials', 'authorize', 'install', 'user', 'config', 'firewall', 'service', 'verify']
const TEARDOWN_STEPS: VpsStepId[] = ['authorize', 'service', 'firewall', 'user', 'install', 'config']

let manifest: VpsManifest | null = null
let busy: VpsBusy = null
let steps: VpsStep[] | null = null
let serviceUp = false
let lastError: string | null = null
let support: { ok: boolean; reason: string | null } = { ok: false, reason: 'Checking…' }
let lockout: VpsStatus['lockout'] = null

const push = (): void => {
  const window = getWindow()
  if (window) window.webContents.send(VPS_IPC.status, status())
}

const setSteps = (ids: VpsStepId[], labels: Partial<Record<VpsStepId, string>> = {}): void => {
  steps = ids.map(id => ({ id, label: labels[id] ?? STEP_LABELS[id], state: 'pending' }))
}

const mark = (id: VpsStepId, state: VpsStep['state'], detail?: string): void => {
  const step = steps?.find(s => s.id === id)
  if (!step) return
  step.state = state
  if (detail !== undefined) step.detail = detail
  push()
}

const failRunning = (message: string): void => {
  const running = steps?.find(s => s.state === 'running')
  if (running) mark(running.id, 'failed', message)
}

const save = (next: VpsManifest | null): void => {
  manifest = next
  if (next) writeManifest(next)
  else removeManifest()
}

const readLockout = (): VpsStatus['lockout'] => {
  const dir = adapter()?.serverDir
  if (!dir || manifest?.state !== 'running') return null
  try {
    const lockFile = join(dir, 'guard.lock')
    const failFile = join(dir, 'guard.fails')
    const until = existsSync(lockFile) ? Number(readFileSync(lockFile, 'utf8').trim()) * 1000 : NaN
    const fails = existsSync(failFile) ? readFileSync(failFile, 'utf8').split(/\r?\n/).filter(l => /^\d+$/.test(l.trim())).length : 0
    return { lockedUntil: Number.isFinite(until) && until > Date.now() ? until : null, recentFailures: fails }
  } catch {
    return null
  }
}

export const status = (): VpsStatus => {
  const m = manifest
  const state: VpsStatus['state'] =
    busy === 'convert'
      ? 'configuring'
      : !m || m.state === 'stopped'
        ? 'disconnected'
        : m.state === 'running'
          ? serviceUp
            ? 'connected'
            : 'unreachable'
          : 'needs-recovery'
  const live = m && (m.state === 'running' || busy === 'convert') ? m : null
  return {
    platform: process.platform,
    support,
    state,
    busy,
    steps,
    server: live
      ? {
          username: live.username,
          port: live.port,
          accessMode: live.accessMode,
          startedAt: live.startedAt,
          hostKeyFingerprint: live.hostKeyFingerprint,
          firewall: live.firewall
        }
      : null,
    passwordAvailable: !!(m?.state === 'running' && getPassword(m.username)),
    tunnel: tunnelStatus(),
    passwordWeak: ((): boolean => {
      const pw = m?.state === 'running' ? getPassword(m.username) : null
      return !!pw && passwordStrength(pw) === 'weak'
    })(),
    keptUser: m?.state === 'stopped' && m.userKept ? m.username : null,
    lockout,
    lastError
  }
}

/** Does the server answer? Updates the pushed status when that changed. */
export const probe = async (): Promise<boolean> => {
  const before = serviceUp
  serviceUp = manifest?.state === 'running' ? await sshAnswers(manifest.port) : false
  lockout = readLockout()
  if (before !== serviceUp) push()
  return serviceUp
}

/** The relay tunnel runs exactly while the server runs in "relay" mode. */
const syncTunnel = (): void => {
  const m = manifest
  const platform = adapter()
  if (m?.state === 'running' && m.accessMode === 'relay' && platform) {
    startTunnel(m.port, platform.serverDir, m.tunnelPort ?? null, port => {
      if (manifest && manifest.tunnelPort !== port) save({ ...manifest, tunnelPort: port })
    })
  } else {
    stopTunnel()
  }
}

export const initVps = async (): Promise<void> => {
  setTunnelListener(push)
  manifest = readManifest()
  const platform = adapter()
  support = platform ? await platform.support() : { ok: false, reason: 'VPS Manager supports Windows 10/11, macOS and Ubuntu.' }
  if (manifest && manifest.platform !== currentPlatform()) {
    logger.warn('[vps] manifest from another platform ignored')
    manifest = null
  }
  if (manifest?.state === 'configuring') logger.warn('[vps] a setup was interrupted; recovery is needed')
  await probe()
  syncTunnel()
  logger.info('[vps] ready', { state: status().state, supported: support.ok })
  push()
}

const exclusive = async <T>(kind: Exclude<VpsBusy, null>, fn: () => Promise<T>): Promise<T> => {
  if (busy) throw new Error('Another VPS operation is still running.')
  busy = kind
  lastError = null
  push()
  try {
    return await fn()
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    lastError = message
    failRunning(message)
    throw error
  } finally {
    busy = null
    await probe()
    push()
  }
}

interface ScriptOutcome {
  ok: boolean
  changes: VpsChange[]
  firewall: VpsFirewallResult | null
  fingerprint: string | null
  /** The script reported an error (and ran its own rollback). */
  error: string | null
  /** macOS would not delete the account: it was disabled and kept (with its files) instead. */
  userKept: boolean
}

/** Run one elevated script, following its progress into the step list. */
const runScript = async (script: string, prompt: string, secret: string | null): Promise<ScriptOutcome> => {
  const outcome: ScriptOutcome = { ok: false, changes: [], firewall: null, fingerprint: null, error: null, userKept: false }
  let authorized = false
  mark('authorize', 'running', 'Waiting for your approval…')
  try {
    const result = await runElevated({
      script,
      prompt,
      ...(secret ? { files: { secret } } : {}),
      onLine: raw => {
        const line = parseScriptLine(redact(raw, [secret]))
        if (!line) return
        if (!authorized) {
          authorized = true
          mark('authorize', 'done', 'Approved')
        }
        if (line.kind === 'step') mark(line.id, line.state, line.detail)
        else if (line.kind === 'change') outcome.changes.push(line.change)
        else if (line.kind === 'firewall') outcome.firewall = line.result
        else if (line.kind === 'fingerprint') outcome.fingerprint = line.value
        else if (line.kind === 'error') outcome.error = line.message
        else if (line.kind === 'ok') outcome.ok = true
        else if (line.kind === 'user-kept') outcome.userKept = true
      }
    })
    if (!authorized) mark('authorize', result.code === 0 ? 'done' : 'failed')
    if (result.code !== 0 && !outcome.error) {
      logger.warn('[vps] elevated script failed without a report', { code: result.code, stderr: redact(result.stderr, [secret]).split('\n')[0]?.slice(0, 500) })
    }
    outcome.ok = outcome.ok && result.code === 0
    return outcome
  } catch (error) {
    if (error instanceof ElevationError) mark('authorize', 'failed', error.message)
    throw error
  }
}

export const convert = (options: VpsConvertOptions): Promise<VpsStatus> => exclusive('convert', () => convertNow(options))

const convertNow = async (options: VpsConvertOptions): Promise<VpsStatus> => {
    const platform = adapter()
    setSteps(SETUP_STEPS)
    push()

    mark('checks', 'running')
    if (!platform || !support.ok) throw new Error(support.reason ?? 'Not supported on this system.')
    if (manifest?.state === 'running') throw new Error('The VPS is already running.')
    if (manifest && manifest.state !== 'stopped') throw new Error('A previous setup did not finish. Use "Clean up" first.')
    mark('checks', 'done')

    mark('port', 'running')
    const port = await pickPort()
    if (!port) throw new Error('Ports 2222–2232 are all in use on this computer.')
    mark('port', 'done', `Port ${port}`)

    mark('credentials', 'running')
    const previous = manifest
    const username = options.username
    const reuseUser = !!(previous?.state === 'stopped' && previous.userKept && previous.username === username)
    const password = options.password ?? newPassword()
    mark('credentials', 'done', `${username}, ${password.length}-character password${reuseUser ? ' (existing account)' : ''}`)

    // Recorded before the prompt: if the app dies mid-setup, Recover knows what to undo.
    save({
      version: 1,
      platform: platform.id,
      state: 'configuring',
      username,
      port,
      accessMode: options.accessMode,
      changes: [],
      firewall: 'unknown',
      hostKeyFingerprint: null,
      userKept: false,
      createdAt: previous?.createdAt ?? Date.now(),
      startedAt: null,
      stoppedAt: null,
      lastError: null
    })
    logger.info('[vps] setup starting', { platform: platform.id, port, reuseUser, firewall: options.firewallConsent })

    let outcome: ScriptOutcome
    try {
      outcome = await runScript(
        platform.setupScript({ username, port, firewall: options.firewallConsent, reuseUser }),
        'Featured App wants to set up an SSH server (VPS) on this computer.',
        password
      )
    } catch (error) {
      // The script never ran (prompt declined / unavailable): nothing changed.
      save(previous)
      throw error
    }

    if (!outcome.ok) {
      if (outcome.error) {
        // The script undid its own changes before exiting — except an account macOS would not let it delete.
        save(outcome.userKept ? keptManifest(manifest as VpsManifest) : previous)
        logger.warn('[vps] setup failed and was rolled back', { error: outcome.error })
        throw new Error(`${outcome.error} Your system was left as it was.`)
      }
      // Stopped without reporting (killed, crashed): keep the record so Clean up can finish the job.
      save({ ...(manifest as VpsManifest), state: 'failed', changes: outcome.changes, lastError: 'Setup stopped unexpectedly.' })
      throw new Error('Setup stopped unexpectedly. Use "Clean up" to remove what was set up.')
    }

    savePassword(username, password)
    save({
      ...(manifest as VpsManifest),
      state: 'running',
      changes: outcome.changes,
      firewall: outcome.firewall ?? 'unknown',
      hostKeyFingerprint: outcome.fingerprint,
      startedAt: Date.now()
    })
    logger.info('[vps] setup finished', { port, changes: outcome.changes, firewall: outcome.firewall })
    syncTunnel()

    // The script checked the port itself; this confirms the app can see it too.
    for (let i = 0; i < 5 && !(await sshAnswers(port)); i++) await new Promise(resolve => setTimeout(resolve, 1000))
    return status()
}

/** The record after an account was kept (disabled) instead of deleted: the next Convert reuses it. */
const keptManifest = (m: VpsManifest): VpsManifest => ({
  ...m,
  state: 'stopped',
  changes: [],
  userKept: true,
  startedAt: null,
  stoppedAt: Date.now(),
  lastError: null
})

const teardown = async (removeUser: boolean, kind: 'disconnect' | 'recover'): Promise<VpsStatus> => {
  const platform = adapter()
  const m = manifest
  if (!platform || !m) throw new Error('There is no VPS to disconnect.')
  // Close the internet way in first: no new visitors while the server is taken down.
  stopTunnel()
  setSteps(TEARDOWN_STEPS, TEARDOWN_LABELS)
  push()
  const outcome = await runScript(
    platform.teardownScript({ username: m.username, port: m.port, changes: m.changes, removeUser }),
    'Featured App wants to stop and remove the SSH server (VPS) it set up.',
    null
  )
  if (!outcome.ok) {
    const message = outcome.error ?? 'Disconnecting did not finish.'
    save({ ...m, lastError: message })
    syncTunnel()
    throw new Error(`${message} The steps marked done were completed; try again to finish.`)
  }
  steps?.forEach(s => {
    if (s.state === 'pending') s.state = 'skipped'
  })
  clearPassword()
  const kept = !removeUser || outcome.userKept
  save(kept ? keptManifest(m) : null)
  logger.info(`[vps] ${kind} finished`, { removeUser, userKept: kept })
  return status()
}

export const disconnect = (options: VpsDisconnectOptions): Promise<VpsStatus> => exclusive('disconnect', () => teardown(options.removeUser, 'disconnect'))

/** After an interrupted setup: remove whatever it left (the account included — it was never used). */
export const recover = (): Promise<VpsStatus> => exclusive('recover', () => teardown(true, 'recover'))

/** Set a new password: the one given (typed in the window), or a strong generated one. */
export const regeneratePassword = (given?: string): Promise<VpsStatus> =>
  exclusive('password', async () => {
    const platform = adapter()
    const m = manifest
    if (!platform || m?.state !== 'running') throw new Error('The VPS is not running.')
    setSteps(['authorize', 'user'])
    const password = given ?? newPassword()
    const outcome = await runScript(platform.passwordScript(m.username), 'Featured App wants to set a new password for the VPS account.', password)
    if (!outcome.ok) throw new Error(outcome.error ?? 'The password was not changed.')
    savePassword(m.username, password)
    steps = null
    logger.info('[vps] password regenerated')
    return status()
  })

/**
 * Change the login. Same username: just the password (one prompt). A new
 * username: disconnect (the old account is deleted, or disabled where macOS
 * will not allow deleting it) and convert again with the new one, keeping the
 * access mode and firewall choice — two prompts.
 */
export const changeLogin = (change: VpsLoginChange): Promise<VpsStatus> => {
  const m = manifest
  if (m?.state !== 'running') return Promise.reject(new Error('The VPS is not running.'))
  if (change.username === m.username) return regeneratePassword(change.password)
  return exclusive('convert', async () => {
    logger.info('[vps] changing the login name')
    await teardown(true, 'disconnect')
    return convertNow({ accessMode: m.accessMode, firewallConsent: m.firewall !== 'declined', username: change.username, ...(change.password ? { password: change.password } : {}) })
  })
}

export const revealPassword = (): string => {
  if (manifest?.state !== 'running') throw new Error('The VPS is not running.')
  const password = getPassword(manifest.username)
  if (!password) throw new Error('The password is not stored on this computer. Use "Regenerate password" to set a new one.')
  return password
}

export const setAccessMode = (mode: VpsAccessMode): VpsStatus => {
  if (manifest) save({ ...manifest, accessMode: mode })
  syncTunnel()
  push()
  return status()
}

export const clearSteps = (): VpsStatus => {
  if (!busy) steps = null
  lastError = null
  push()
  return status()
}

export const systemInfo = async (): Promise<VpsSystemInfo> => {
  const cpu = cpus()
  const disk = await monitor.diskUsage()
  return {
    os: process.platform === 'darwin' ? 'macOS' : process.platform === 'win32' ? 'Windows' : (linuxPrettyName() ?? 'Linux'),
    osVersion: process.getSystemVersion(),
    arch: process.arch,
    cpuModel: cpu[0]?.model.trim() ?? 'Unknown',
    cpuCores: cpu.length,
    totalMemory: totalmem(),
    disk: disk ? { total: disk.total, free: disk.total - disk.used } : null,
    hostname: hostname()
  }
}

export const metrics = async (): Promise<VpsMetrics> => {
  const running = await probe()
  const m = manifest
  const bootedAt = Date.now() - uptime() * 1000
  const [disk, network, connections] = await Promise.all([
    monitor.diskUsage(),
    monitor.netRates(),
    running && m ? monitor.activeConnections(m.port) : Promise.resolve(null)
  ])
  return {
    cpuPercent: monitor.cpuPercent(),
    memory: monitor.memory(),
    disk,
    network,
    systemUptime: monitor.systemUptime(),
    serverUptime: running && m?.startedAt ? (Date.now() - Math.max(m.startedAt, bootedAt)) / 1000 : null,
    activeConnections: connections,
    serviceRunning: running
  }
}
