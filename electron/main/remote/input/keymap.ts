/** The key number for `code` on `platform`, or null when the host has no such key. */
export const keyFor = (code: string, platform: 'darwin' | 'win32' | 'linux'): number | null => {
  const entry = KEYMAP[code]
  if (!entry) return null
  const value = platform === 'darwin' ? entry[0] : platform === 'win32' ? entry[1] : entry[2] + 8
  return value < 0 ? null : value
}
